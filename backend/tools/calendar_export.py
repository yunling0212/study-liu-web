"""学习计划 → .ics 日历文件 —— v19 第三梯队 #13-A。

设计：
- 零外部依赖（手写 RFC 5545 输出，不依赖 ics 库）
- 一门课 = 一个 VEVENT，每天一条全天事件
- 描述包含：第几天 / 任务 / 关联章节
- 时间从今天开始逐天推进（默认 7 天，可按 plan 长度自适应）
- 输出：Google Calendar / 苹果日历 / Outlook 都能直接导入

输入格式（run_plan_pipeline 返回的 result）——**两种 plan 形态都要吃下**：

1) 真实 pipeline 输出（agents/writer.py）是**字符串列表**：
   {
       "course": "Python 入门",
       "plan": [
           "第1天：通读章节内容，标记不懂的概念——环境搭建 与 基础语法",
           "第2天：看配套视频课程，对照笔记补全关键点——基础语法 与 控制流程",
           ...
       ]
   }

2) 早期/测试用的结构化 dict 列表：
   {
       "course": "Python 入门",
       "plan": [
           {"day": 1, "title": "...", "tasks": ["..."], "chapters": ["..."]},
           ...
       ]
   }

形态 1 由 `_normalize_day` 归一化成形态 2 再渲染，
**绝不能对字符串静默 continue**——那样导出的 .ics 会是 0 个事件（空的）。
"""

